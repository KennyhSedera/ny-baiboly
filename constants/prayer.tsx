export function getDailyPrayer() {
  const now = new Date();

  const seed =
    now.getFullYear() * 10000 +
    (now.getMonth() + 1) * 100 +
    now.getDate();

  const randomSeed = Math.sin(seed) * 10000;
  const random = randomSeed - Math.floor(randomSeed);

  const index = Math.floor(random * dailyPrayers.length);

  return dailyPrayers[index];
}